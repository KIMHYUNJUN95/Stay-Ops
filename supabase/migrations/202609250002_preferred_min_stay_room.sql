-- 듀얼 유닛 방에서 **최소숙박·재고를 어느 유닛에 쓸 것인가** (2026-09-25).
--
-- WHY THIS EXISTS
-- ---------------
-- 한 캘린더 행 뒤에 Beds24 방 계정이 둘 이상일 수 있다. 쓰기 대상은 그 날짜의 **활성 유닛**
-- (`1 ≤ minStay < 50`)인데, 활성이 **둘 이상인 날짜가 실제로 있다.**
--
-- 2026-09-25 실측 (2026-09-25 ~ 2027-03-31, 188일):
--
--   아라키초A·가부키초 듀얼 21개 방   →  10/01~10/04 **4일**  (유닛 교체 구간)
--   다카다노바바 401호                →  **188일 전부**
--   오쿠보C                           →  0일
--
-- 교체 구간은 이런 모양이다 (아라키초A 201호):
--
--   09/29~09/30   383971 m=2 (판매)   601545 m=99 (잠금)
--   10/01~10/04   383971 m=2 (판매)   601545 m=2  (판매)   ← 둘 다 활성
--   10/05~        383971 m=50(잠금)   601545 m=2  (판매)
--
-- 활성이 둘일 때 어느 쪽에 쓸지는 **Beds24 설정에만 있는 사실**이라 규칙으로 못 만든다.
-- 저쪽(STAY ARI Manager)도 같은 결론이라 `PREFERRED_DUAL_ROOM_IDS` 표를 하드코딩했다.
-- 우리는 코드 대신 여기에 둔다 — 방이 늘거나 교체돼도 배포 없이 채울 수 있다.
--
-- 기본은 「활성 전부에 쓴다」다 (2026-09-25 확정)
-- ---------------------------------------------
-- 하나만 쓰면 **화면의 숫자가 안 바뀐다.** 표시는 활성 유닛들의 **가장 짧은** minStay 인데,
-- 다른 활성 유닛이 더 짧은 값을 들고 있으면 한쪽만 고쳐도 표시가 그대로다. 저쪽이 가부키초
-- 803호에서 겪고 하드코딩으로 때운 자리가 이것이다.
--
-- 그래서 이 컬럼은 **보통 비어 있다.** 특정 유닛에만 써야 하는 예외가 생길 때만 채운다.
--
-- **잠긴 유닛에는 절대 쓰지 않는다.** Beds24 에 「비활성」 스위치가 따로 없고 `minStay ≥ 50`
-- 이 곧 잠금이라, 거기에 `1` 을 쓰면 잠금이 풀려 **같은 방이 두 listing 으로 팔린다.**
--
-- NOTE — 가격은 여기와 무관하다
-- -----------------------------
-- 가격은 `external_price_source_room_id`(가격 소스)로 간다. 자식 유닛은 자기 가격이 없고
-- 소스의 `price1` 에서 계산된다(실측: `priceLinking.offsetMultiplier` — Booking 1.48 /
-- Agoda 1.35 / Homepage 1). **가격 소스와 활성 유닛은 서로 다른 축이다** —
-- 아라키초A 501호는 소스가 활성 유닛이고, 201호는 소스가 잠긴 유닛이다.

alter table public.rooms
  add column if not exists preferred_min_stay_room_id text;

comment on column public.rooms.preferred_min_stay_room_id is
  '예외 지정. 여기 적힌 Beds24 roomId 가 그 날짜에 활성이면 최소숙박·재고를 그 유닛에만 쓴다. 잠긴 유닛을 적어두면 무시된다. 보통 비어 있고, 그때는 활성 유닛 전부에 쓴다.';
