-- `memberships.manage_users` 제거 — 위임을 권한 키로 옮겼다 (2026-09-10).
--
-- 설계: docs/engineering/14-permission-architecture.md §9(기존 개인 단위 장치 흡수)
--
-- 사용자 관리 화면 접근은 「개발자 기본 + 개인 위임」이다(2026-07-13 모델). 위임 수단이 이
-- 불리언이었는데 **감사 기록이 없었다** — 누가 언제 왜 줬는지 남지 않고 회수 이력도 없다.
-- 권한 부여(`user.manage`)는 부여자·사유·회수를 함께 남기고, 사이드바·페이지 게이트가 같은 키를
-- 본다.
--
-- **지우기 전에 확인한 것(2026-09-10 실측):**
-- - 이 플래그를 가진 사용자 **0명** — 옮길 데이터가 없다.
-- - 이 컬럼을 참조하는 RLS 정책 **0개**.
-- - 앱 코드의 읽기·쓰기는 이 커밋에서 모두 제거했다.
--
-- 쓰이지 않는 컬럼을 남겨 두면 다음 사람이 「이건 왜 항상 비어 있지」로 시간을 쓴다
-- (채용 모듈에서 같은 이유로 컬럼 3개를 지운 전례가 있다 — 202609090003).
alter table public.memberships drop column if exists manage_users;
