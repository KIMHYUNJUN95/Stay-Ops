/**
 * 판매 캘린더 격자 칸의 가격 표기 — `42659` → `42.7K`. 데스크톱 · 모바일 격자가 **같은 함수**를 쓴다
 * (2026-10-02 사용자 지시 「모바일도 대시보드처럼 38K」 — 예전 모바일은 `54,900` 전부 · 10만 이상만 `k`).
 *
 * 칸 폭이 좁아 `¥42,659` 는 들어가지 않는다. 천 단위로 줄이되 **소수 한 자리는 남긴다** — `42K` 와 `43K` 로
 * 뭉개면 2,000엔 차이가 사라져 가격표를 읽는 의미가 없어진다. 딱 떨어지면 `.0` 은 뗀다(`38K`).
 */
export function formatGridPrice(value: number): string {
  return `${(value / 1000).toFixed(1).replace(/\.0$/, "")}K`;
}
